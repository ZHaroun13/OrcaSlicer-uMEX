class _TextPath:
    """The fields of v2's PathRec that compare_planner.clearance reads."""
    def __init__(self, kind, points, width):
        self.kind, self.points, self.width = kind, points, width


def _wider_segments(t, kind, pts, width):
    """The segments of a dumped text path printed wider than its first-segment width (review fix 3), as 2-point
    obstacles at their own ;WIDTH:."""
    out = []
    for i, w in enumerate(t.get("seg_width") or []):
        w = float(w)
        if w > width and i + 1 < len(pts) and pts[i] != pts[i + 1]:
            out.append(_TextPath(kind, [pts[i], pts[i + 1]], w))
    return out


def dump_text_model(dj):
    """The planner's own text input of a dumped layer (text walls, open outer walls, text paste) as T3 obstacles."""
    import types
    paths = []
    for key, kind in (("text_walls", "wall"), ("open_outer", "wall"), ("text_paste", "paste")):
        for t in dj["input"].get(key, []):
            if not isinstance(t, dict) or "pts" not in t:
                continue
            pts = [(float(x), float(y)) for x, y in t["pts"]]
            if len(pts) >= 2:
                paths.append(_TextPath(kind, pts, float(t["width"])))
                paths += _wider_segments(t, kind, pts, float(t["width"]))
    return types.SimpleNamespace(paths=paths)


def seam_discs(models, delta, gap, sg):
    """Discs of radius w + delta + gap around both ends of every outer-wall path of the given v2 LayerModels: the
    seam point (path start) and, with a seam gap, the clipped end, gap short of it."""
    discs = []
    for model in models:
        for p in model.paths:
            if p.kind == "wall" and p.ptype == "outer wall" and p.points:
                for q in (p.points[0], p.points[-1]):
                    discs.append(sg.Point(q).buffer(p.width + delta + gap, quad_segs=16))
    return sg.unary_union(discs) if discs else None


def t5_band_model(E, model0, model15, native):
    """T5(iv) reference model: v2's own LayerModel of the 15 % text (its walls renamed so they form no ring, its
    paste and sparse paths as they are) plus the native wall pieces (native_band_model), with the 0 % outer /
    overhang walls added as zero-width paths: the solid S is the 0 % one (v2 cannot close the 15 % rings) and the
    band and paste are the inputs the native planner used for the 15 % block, B_text(15 %) U B_native. The 0 %
    text differs from them near each seam by the 3-decimal rounding of the seam vertex that Orca inserts into the
    loop's text, and the concentric solid infill is itself clipped by the seam gap (Fill loop_clipping); at the
    acute tips of the notch either moves Omega by microns."""
    import copy
    import dataclasses
    m = copy.copy(model0)
    paths = [p for p in model15.paths if p.kind != "wall"]
    paths += [dataclasses.replace(p, width=0.0) for p in model0.paths
              if p.kind == "wall" and p.ptype in ("outer wall", "overhang wall")]
    paths += [dataclasses.replace(p, ptype="seam-gap text wall") for p in model15.paths if p.kind == "wall"]
    m.paths = paths
    return native_band_model(E, m, native)


def t5_job(job):
    """T5 for one part and wall generator: the part exported with the shadow on (and the dump) at seam_gap 0 % and at
    15 %; v2 run on both texts (records stripped).
      T5i   v2 at 15 % gives st=open, or no plan, on at least one core layer (the test reaches v2's weakness);
      T5ii  native at 15 % gives st ok / small on every core layer, its core set equals the 0 % slice's, and its
            planner summary is clean;
      T5iii native 15 % vs native 0 % per layer (ca / oa / ra relative difference, Omega and run Hausdorff, which
            text-derived inputs changed): reported only, never failed;
      T5iv  native 15 % against v2 0 % with the T2(c) tolerances (compare_t2c), seam discs of radius w + delta + gap
            around both ends of the outer walls of both texts, BEGIN k z h s F fu fp st string-equal;
      T5v   T3 on every 15 % block against the 15 % text (planner input walls, open outer walls and paste) and the
            native closed loops, RUN points inside the native solid; diw_translate accepts both files."""
