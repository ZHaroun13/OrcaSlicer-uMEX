def main_matrix(argv):
    from concurrent.futures import ProcessPoolExecutor
    import platform
    engine = opt(argv, "--engine")
    orca = opt(argv, "--orca")
    tr = opt(argv, "--translate")
    datadir = opt(argv, "--datadir")
    work = opt(argv, "--work")
    nj = int(opt(argv, "-j", "4"))
    only = opt(argv, "--only")
    rep = Report()
    if not (engine and orca and tr and datadir and work):
        print(__doc__)
        return 2
    for nm, p in (("exe.orca", orca), ("exe.translate", tr)):
        rep.check(nm, os.path.isfile(p), p)
    rep.check("datadir", os.path.isdir(datadir), datadir)
    rep.check("engine", os.path.isfile(os.path.join(engine, "diw_engine.py")), engine)
    if rep.fails:
        print(f"{rep.n} checks, {len(rep.fails)} failures")
        return 1
    E, sg, shapely = _engine(engine)
    from compare_powder import PINNED
    versions = {"python": platform.python_version(), "shapely": shapely.__version__, "geos": shapely.geos_version_string}
    print(f"versions: {versions}")
    if versions != PINNED and "--allow-version-drift" not in argv:
        print(f"version drift from {PINNED}; pass --allow-version-drift to run anyway")
        return 2
    with open(tr, "rb") as fh:
        rep.check("exe.translate.flags", b"--plan-records" in fh.read(), "--plan-records present")
    os.makedirs(work, exist_ok=True)
    t0 = time.time()
    mdirs = {None: make_meshes(work, DEFAULT_DELTA)}
    for fname, fov in FACTORS.items():
        if "diw_shell_powder_clearance" in fov:
            d = float(fov["diw_shell_powder_clearance"])
            mdirs[d] = make_meshes(work, d)

    slice_only = "--slice-only" in argv
    t5_mode = "--t5" in argv
    stress = "--stress" in argv
    # T10 first, alone on the machine (timing)
    if "--no-t10" not in argv and (only is None or "T10" in only) and not slice_only and not t5_mode and not stress:
        t10(rep, orca, datadir, mdirs[None], work)

    jobs = []
    t5 = []
    if t5_mode:
        for part in T5_PARTS:
            for wname, wov in WALLS.items():
                if only and only not in f"T5.{part}.{wname}":
                    continue
                t5.append({"part": part, "walls": wname, "overrides": dict(wov), "work": work, "orca": orca,
                           "translate": tr, "datadir": datadir, "engine": engine, "mdir": mdirs[None]})
    for part, vname, ov in ([] if t5_mode or stress else matrix_jobs()):
        name = f"{part}.{vname}"
        if only and only not in name:
            continue
        d = float(ov["diw_shell_powder_clearance"]) if "diw_shell_powder_clearance" in ov else None
        jobs.append({"part": part, "variant": vname, "overrides": ov, "work": work, "orca": orca, "translate": tr,
                     "datadir": datadir, "engine": engine, "mdir": mdirs[d], "reuse": opt(argv, "--reuse")})
    for part, vname, ov, env in (STRESS if stress else []):
        name = f"{part}.{vname}"
        if only and only not in name:
            continue
        jobs.append({"part": part, "variant": vname, "overrides": dict(ov), "env": dict(env), "stress": True,
                     "work": work, "orca": orca, "translate": tr, "datadir": datadir, "engine": engine,
                     "mdir": mdirs[None], "reuse": None})
    t4 = []
    if "--no-t4d" not in argv and not slice_only and not t5_mode and not stress:
        for part in T4D_PARTS:
            if only and only not in f"T4d.{part}":
                continue
            t4.append({"part": part, "work": work, "orca": orca, "datadir": datadir, "engine": engine, "mdir": mdirs[None]})
    print(f"{len(jobs)} matrix slices, {len(t4)} T4(d) parts, {len(t5)} T5 slices, {nj} workers", flush=True)
    results = []
    with ProcessPoolExecutor(max_workers=nj) as ex:
        futs = [ex.submit(slice_only_job if slice_only else slice_job, j) for j in jobs] + \
               [ex.submit(t4d_job, j) for j in t4] + [ex.submit(t5_job, j) for j in t5]
        for f in futs:
            r = f.result()
            results.append(r)
            nf = sum(1 for x in r["records"] if not x[2])
            inf = r["info"]
            print(f"  {r['name']}: {len(r['records'])} checks, {nf} failures, core {inf.get('core')}, "
                  + (f"st {inf.get('st')}, slice {inf.get('slice_s', 0):.1f} s, " if slice_only else
                     f"T2c layers {inf.get('t2c_layers')}, ")
                  + (f"v2 at {T5_GAP} (open, no plan, planned, of core) {inf.get('v2_15')}, T5iv layers "
                     f"{inf.get('t5iv_layers')}, " if "v2_15" in inf else "")
                  + f"{inf.get('seconds', 0):.0f} s"
                  + (f", summary {inf['summary']['reasons']}" if inf.get("summary") else ""), flush=True)

    # aggregate
    by_kind, logs = {}, []
    tot = new_stats()
    for r in results:
        for kind, name, ok, detail in r["records"]:
            rep.n += 1
            k = by_kind.setdefault(kind, [0, 0])
            k[0] += 1
            if not ok:
                k[1] += 1
                rep.fails.append(f"{kind} {name}: {detail}")
        logs += r["logs"]
        sc = r["stats"].get("components", 0) if r["stats"] else 0
        if sc:
            # review fix 9: T2(c) uses the T1 tolerances, which include "excluded D5 fraction < 5 %"
            d5 = r["stats"].get("d5_excluded", 0)
            ok = d5_fraction_ok(d5, sc)
            rep.n += 1
            k = by_kind.setdefault("D5", [0, 0])
            k[0] += 1
            if not ok:
                k[1] += 1
                rep.fails.append(f"D5 {r['name']}.excluded_fraction: {d5}/{sc} components without hatch comparison")
        for key, v in r["stats"].items():
            if key in ("t3_min", "t3_min_rounded", "t3_v2_min"):
                tot[key] = min(tot.get(key, math.inf), v)
            elif isinstance(v, (int, float)) and key.startswith(("haus", "max_", "fb_pos")):
                tot[key] = max(tot.get(key, 0.0), v)
            else:
                tot[key] = tot.get(key, 0) + v
    if tot.get("components", 0):
        d5, sc = tot.get("d5_excluded", 0), tot["components"]
        rep.n += 1
        k = by_kind.setdefault("D5", [0, 0])
        k[0] += 1
        if not d5 / sc < 0.05:
            k[1] += 1
            rep.fails.append(f"D5 all.excluded_fraction: {d5}/{sc} = {d5 / sc:.3%}")
    print("\nT3 minimum slack per slice (native / v2 record values, mm):")
    for r in results:
        s = r["stats"]
        if s and s.get("t3_min", math.inf) != math.inf:
            print(f"  {r['name']}: {s['t3_min']:.4g} (rounded {s['t3_min_rounded']:.4g}); v2 {s['t3_v2_min']:.4g}")
    print("\nplanner warnings:")
    for r in results:
        for w in r["info"].get("warnings", []):
            print(f"  {r['name']}: {w}")
    if t5_mode:
        print(f"\nT5(iii) reported metric, native {T5_GAP} vs native 0 % (not asserted; expected <= 1e-6 relative and "
              f"<= 0.5 um): worst (ca rel, oa rel, ra rel, ra abs mm2, Omega Hausdorff mm, run/point Hausdorff mm)")
        for r in results:
            m = r["info"].get("t5iii")
            if m is None:
                continue
            w = "n/a" if m["worst"] is None else ", ".join(f"{x:.3g}" for x in m["worst"])
            print(f"  {r['name']}: {m['layers']} layers; worst ({w}); within expected {m['within_expected']}; "
                  f"text inputs changed {m['inputs_changed']}")
            for row in m["over"]:
                print(f"      over: k{row[0]} ca {row[1]:.3g} oa {row[2]:.3g} ra {row[3]:.3g} ({row[4]:.3g} mm2) "
                      f"Omega {row[5]:.3g} runs {row[6]:.3g} same run count {row[7]} same nc {row[8]}")
    tower = [r["name"] for r in results if r["info"].get("tower")]
    print(f"\nslices with a prime tower in the G-code: {tower}")
    if slice_only:
        sup = [r["name"] for r in results if r["info"].get("support")]
        print(f"slices with support in the G-code: {sup}")
        nb = sum(r["info"].get("core", (0, 0, 0))[0] for r in results)
        nc = sum(r["info"].get("core", (0, 0, 0))[1] for r in results)
        print(f"stage 5a totals: {len(results)} slices, {nb} native blocks, {nc} v2 text-core layers")
    for l in logs[:40]:
        print("LOG  " + l)
    if len(logs) > 40:
        print(f"LOG  ... {len(logs) - 40} more")
    print("per kind (checks, failures): " + ", ".join(f"{k} {v[0]}/{v[1]}" for k, v in sorted(by_kind.items())))
    print("stats: " + ", ".join(f"{k}={v:.4g}" if isinstance(v, float) else f"{k}={v}" for k, v in tot.items()))
    with open(os.path.join(work, "failures.txt"), "w", encoding="utf-8") as fh:
        fh.writelines(f + "\n" for f in rep.fails)
    for f in rep.fails[:60]:
        print("  FAIL " + f[:400])
    if len(rep.fails) > 60:
        print(f"  ... {len(rep.fails) - 60} more in {os.path.join(work, 'failures.txt')}")
    print(f"{rep.n} checks, {len(rep.fails)} failures ({time.time() - t0:.0f} s)")
    return 1 if rep.fails else 0


def main(argv):
    if "--matrix" in argv:
        return main_matrix(argv)
    return main_stage4(argv)


if __name__ == "__main__":
    sys.exit(main(sys.argv))
