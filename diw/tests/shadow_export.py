def v2_text_core(E, data):
    """v2's own text classification (scan_gcode / split_layers / classify_layers with the file's N_bottom / N_top) of
    the records-free G-code: {k: reason} of the core layers, and the chunk count."""
    from compare_powder import parse_config_block, v2_config
    cfg = v2_config(parse_config_block(data), E)
    cfg["enable_u_mex_powder_infill"] = True
    P = E.UMexParams.from_config(cfg)[0]
    lines = data.decode("utf-8", "replace").splitlines(keepends=True)
    infos = E.scan_gcode(lines)
    chunks = E.split_layers(lines, infos)
    E.classify_layers(chunks, P.n_bottom, P.n_top)
    return {c.index: c.reason for c in chunks if c.is_core}, len(chunks), P


