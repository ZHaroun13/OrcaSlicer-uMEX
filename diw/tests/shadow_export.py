def shifted_stl(src, dst, dx, dy):
    out = []
    with open(src) as fh:
        for line in fh:
            s = line.strip()
            if s.startswith("vertex "):
                x, y, z = (float(v) for v in s.split()[1:4])
                out.append("   vertex %.12g %.12g %.12g\n" % (x + dx, y + dy, z))
            else:
                out.append(line)
    with open(dst, "w", newline="\n") as fh:
        fh.writelines(out)


