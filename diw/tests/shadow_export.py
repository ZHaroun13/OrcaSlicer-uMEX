class Collector:
    """compare_planner.Checks-compatible collector of (kind, name, ok, detail) records, picklable."""
    def __init__(self):
        self.n = 0
        self.fails = []
        self.logs = []
        self.by_kind = {}
        self.records = []

    def check(self, kind, name, ok, detail=""):
        self.records.append((kind, name, bool(ok), detail))
        self.n += 1
        k = self.by_kind.setdefault(kind, [0, 0])
        k[0] += 1
        if not ok:
            k[1] += 1
            self.fails.append(f"{kind} {name}: {detail}")
        return ok

    def log(self, msg):
        self.logs.append(msg)


def d5_fraction_ok(d5, components):
    """Review fix 9: the D5 exclusion (components whose H/s is within 2 um/s of an integer skip the hatch comparison)
    is bounded per slice: under 5 % of the components, or at most one excluded component on a slice with fewer than
    20 (one exclusion is then already 5 % or more)."""
    return components > 0 and (d5 / components < 0.05 or (components < 20 and d5 <= 1))


