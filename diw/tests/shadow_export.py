"""End-to-end shadow planner harness (diw/PLANNER_DESIGN.md section 10: T2, T3, T4(d), T6, T7, T10).

usage:
  python shadow_export.py --orca <orca-slicer.exe> --translate <diw_translate.exe> --datadir <orca datadir>
                          --work <dir> [--pre <dir>] [--parts cube25,two_objects]
  python shadow_export.py --orca <orca-slicer.exe> --datadir <orca datadir> --work <dir> --make-pre <dir>
                          [--parts ...]
  python shadow_export.py --matrix --engine <v2 engine dir> --orca <orca-slicer.exe> --translate <diw_translate.exe>
                          --datadir <orca datadir> --work <dir> [-j N] [--only <substring>] [--no-t10] [--no-t4d]
                          [--allow-version-drift] [--slice-only] [--reuse <stage-5a work dir>]
                          (--only T10 runs T10 alone; --only T4d. runs T4(d) alone)
  python shadow_export.py --matrix --t5 <same arguments> [--only T5.<part>.<walls>]

Slices with the OrcaSlicer CLI, the DIW printer (profiles/flat_machine_diw.json) and the powder process
(profiles/flat_process_powder.json), with ORCA_DIW_EXPORT_UNTRANSLATED=1 so the raw file with the records is kept.
Meshes come from planner_meshes.py (and tests/data/*.obj). "norm" blanks the "; generated by ... at <time>" header
line, "strip" removes the ;DIW: lines.

Default mode (stage 4 subset: cube25, two_objects). Each part is exported as
  kill      ORCA_DIW_NO_NATIVE_PLAN=1 (the kill switch)
  on        the shadow planner on
  capture, plan, binder
            ORCA_DIW_SHADOW_FAULT=<point> (fault injection, T6)
and checked:
  T7  rc, strip(on) == kill, equal GCodeProcessor statistics, kill == pre (with --pre), kill carries no records;
  T2a no ;DIWP line, every ;DIW:BEGIN after a start marker, at least one block;
  T2b diw_translate --config-from-gcode <on> exits 0 in powder mode;
  T6  for each fault: export exits 0, the planner warning is in the log, no ;DIWP line, strip == kill.
--make-pre writes the export of the given (pre-increment) build into <dir>/<part>.gcode instead.

--matrix (stage 5): the section 10.1 matrix at seam_gap 0 (see MATRIX below), every slice exported as
  kill  (kill switch), on (shadow on), keep (ORCA_DIW_SHADOW_KEEP_PLACEHOLDERS=1 + ORCA_DIW_SHADOW_DUMP=<dir>)
and checked:
  T2a  rc; norm(strip(on)) == norm(kill); no ;DIWP line; every BEGIN right after a start-marker line; keep without
       its ;DIWP lines == on (the dump and the kept placeholders change nothing else); the planner summary has no
       disagreement, no lost / frame / plan / record / capture count and max_held <= 1 (T10 debug counter);
  T2b  diw_translate --config-from-gcode <on> exits 0 (powder mode);
  T2c  v2 (v2_hooks.capture_geometry on the kill export) against the native blocks, paired by k: the core sets are
       equal (a difference only where the planner logged merged_multi_core / plan, D6 / D8); BEGIN k z h s F fu fp
       and st string-equal; STAT / RUN / FB with the T1 tolerances (compare_planner.compare_arbitrated), C and
       Omega Hausdorff taken outside a disc of radius w + delta + gap around each seam point (outer-wall path start);
       the dumped record equals the exported block;
  T2d  diw_translate --plan-records on the keep export, with the dump reloaded (a copy) and the placeholders kept,
       reproduces the keep export byte for byte;
  T2e  section-aware diff of translate(on) against translate(v2's records on the kill export): byte-identical
       outside the S4 bodies and the fallback (FB) lines of S1;
  T3   every RUN segment / point dwell of every native block: (dist - w/2) to the text walls, the text paste and
       the native closed wall loops >= delta + guard - 10 nm; >= delta after rounding to 3 decimals; inside the
       native solid S; minimum slack reported per slice beside v2's.
  T4d  cube25, cone and lshape placed with --arrange 0 at (70, 70) and moved by (1, 1) um and (10, 10) um: the same
       k set and BEGIN k z h s F fu fp; st and nc equal; C (10 um opening), Omega, runs, point dwells and FB points,
       translated back, within 1.5 um.
  T10  cube25 and cone: wall time of the CLI export with the shadow on <= 1.2 x the kill-switch time (best of 3).
--matrix --reuse <dir> (stage 5b): the "on" run of each slice is the stage-5a export <dir>/slices/<slice>/on
  (plate_1.gcode + log.txt) instead of a new export; kill and keep are exported and compared against it.
--matrix --t5 (stage 6a): T5 only (t5_job): cube25, ring, notch and lshape, classic and Arachne walls, each exported
  with the shadow on at seam_gap 0 % and 15 % (ORCA_DIW_TEST_KEEP_SEAM_GAP=1, since a DIW printer otherwise forces
  the seam gap to 0); T5 i, ii, iv, v asserted, iii reported.
--matrix --stress (stage 6b): the section 10.1 stress variants (STRESS below: by-object sequential printing, objects
  at 0.2 and 0.3 mm layer height via an assemble list, pressure equalizer + fan_speedup_time + cooling slowdown, arc
  fitting, scarf seam, policy=error with an overflow), each through the full slice_job (T2 a-e, T3), plus S6: the
  overrides reached the config block, no block on an arc / G91 chunk, and each variant reaches what it stresses
  (G2/G3 on otherwise-core chunks, both layer heights, z drops between objects, a z ramp in the outer wall).
  ORCA_DIW_TEST_KEEP_FDM=1 keeps arc fitting and the cooling slowdown on the DIW printer for those variants.
  policy=error: every core layer carries the st=open carrier, and v2 and the translator abort with the same message
  at the first one (T2b / T2c); T2(e) has no output to diff there.
--matrix --slice-only (stage 5a): every matrix slice exported once with the shadow on (no kill / keep runs, no v2
  planning, no T2-T4 / T10); checks S5a (slice_only_job): rc, overrides in the config block, no ;DIWP, records parse,
  placement, clean summary, native blocks exactly on v2's text-core layers of the same file, and
  diw_translate --config-from-gcode exits 0.
Prints "N checks, F failures" and exits non-zero on any failure. A missing executable or input is a failure.
"""
