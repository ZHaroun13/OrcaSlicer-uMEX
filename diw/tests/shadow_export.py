def stress_reach(E, chk, info, name, part, ov, kill, on):
    """Checks that a stress variant reaches what it stresses, and that no block sits on an arc / G91 chunk."""
    cb = parse_cfg(kill)
    wrong = {k: (v, cb.get(k)) for k, v in ov.items() if str(cb.get(k, "<absent>")).strip() != v}
    chk.check("S6", f"{name}.settings", not wrong, f"{len(ov)} override(s) in the config block" +
              (f"; wrong {wrong}" if wrong else ""))
    text = kill.decode("utf-8", "replace")
    lines = text.splitlines(keepends=True)
    infos = E.scan_gcode(lines)
    chunks = E.split_layers(lines, infos)
    nat = begin_lines(on)
    arc = {c.index for c in chunks if c.has_arc or c.has_relxyz}
    # an arc / G91 chunk that would be core by the auto rule without its arcs (gate 2 is what drops it)
    arc_core = {c.index for c in chunks if c.index in arc and c.index != len(chunks) and
                c.types & E.SPARSE_TYPES and not c.types & E.SKIN_TYPES}
    on_arc = sorted(set(nat) & arc)
    chk.check("S6", f"{name}.no_block_on_arc", not on_arc,
              f"{len(arc)} arc/G91 chunk(s) ({len(arc_core)} otherwise core), {len(nat)} block(s), none on them"
              if not on_arc else f"blocks on arc/G91 chunks {on_arc[:10]}")
    info["arc_chunks"] = (len(arc), len(arc_core))
    if ov.get("enable_arc_fitting", "disabled") == "sparse_infill":
        # rectilinear sparse infill fits to linear moves only: the path takes the writer's arc branch but prints G1
        # (the capture's arc predicate must not count it; the summary check above has no disagreement)
        n23 = sum(1 for i in infos if i.is_motion and i.is_arc)
        chk.check("S6", f"{name}.arcs_sparse_reached", True, f"{n23} G2/G3 line(s); {len(nat)} block(s)")
    elif ov.get("enable_arc_fitting", "disabled") != "disabled":
        n23 = sum(1 for i in infos if i.is_motion and i.is_arc)
        chk.check("S6", f"{name}.arcs_reached", len(arc_core) > 0,
                  f"{n23} G2/G3 line(s); {len(arc_core)} otherwise-core chunk(s) excluded by the arcs")
    if part in ASSEMBLE:
        # each object's own layer grid is printed: first layer z0, then z0 + lh and z0 + 2 lh for each layer height
        hs = sorted({round(c.height, 4) for c in chunks if c.height})
        zs = [c.z for c in chunks if c.z is not None]
        steps = sorted({round(b - a, 4) for a, b in zip(zs, zs[1:])})
        z0, zset = min(zs), {round(z, 3) for z in zs}
        want = {round(z0 + n * float(pp["layer_height"]), 3) for _, pp in ASSEMBLE[part] for n in (1, 2)}
        chk.check("S6", f"{name}.heights_reached", want <= zset,
                  f"z {sorted(want)} all printed; ;HEIGHT values {hs}; z steps between chunks {steps[:12]}"
                  if want <= zset else f"missing z {sorted(want - zset)}")
        info["z_steps"] = steps[:12]
    if ov.get("print_sequence") == "by object":
        # by-object order: the z sequence of the chunks drops back at least once
        zs = [c.z for c in chunks if c.z is not None]
        drops = sum(1 for a, b in zip(zs, zs[1:]) if b < a - 1e-9)
        chk.check("S6", f"{name}.sequential_reached", drops >= 1, f"{drops} z drop(s) between chunks")
    if ov.get("seam_slope_type", "none") != "none":
        # a scarf seam ramps z inside the outer wall
        wall_z = 0
        for c in chunks:
            zs = {round(infos[i].z1, 4) for i in range(c.start, c.end)
                  if infos[i].is_extruding_move and infos[i].ftype in ("outer wall", "external perimeter")}
            wall_z += len(zs) > 1
        chk.check("S6", f"{name}.scarf_reached", wall_z > 0, f"{wall_z} chunk(s) with a z ramp in the outer wall")
    if ov.get("slow_down_for_layer_cooling") == "1":
        # the cooling slowdown reached its floor (slow_down_min_speed, mm/s -> F mm/min) on some moves
        fmin = f" F{int(round(float(ov.get('slow_down_min_speed', '10')) * 60))}"
        n = text.count(fmin)
        chk.check("S6", f"{name}.cooling_reached", n > 0, f"{n} move(s) at{fmin} (slow_down_min_speed)")


def policy_error_checks(E, B, H, chk, info, name, sdir, tr, kill_path, on, keep, keep_path, dump_dir):
    """policy=error with an overflow (section 6.3 gate 8, section 8): every core layer gets the st=open carrier with
    F = fu = f_calc and s = s_hatch, and the translator aborts with v2's own message at v2's layer."""
    from compare_powder import parse_config_block, v2_config
    kill = open(kill_path, "rb").read()
    cfg = v2_config(parse_config_block(kill), E)
    cfg["enable_u_mex_powder_infill"] = True
    P = E.UMexParams.from_config(cfg)[0]
    # v2 on the kill export: the abort message
    v2_msg = None
    out = os.path.join(sdir, "v2.policy_error.gcode")
    try:
        E.DIWPostProcessor(cfg).process_file(kill_path, out)
    except E.UMexConfigError as ex:
        v2_msg = str(ex)
    chk.check("T2b", f"{name}.v2_aborts", v2_msg is not None and "exceeds powder_f_max" in v2_msg,
              repr(v2_msg)[:200])
    # T2(b): the translator aborts with v2's exact message
    tr_nat = os.path.join(sdir, "on.translated.gcode")
    rc, err = run_tr(tr, ["--config-from-gcode", os.path.join(sdir, "on", "plate_1.gcode"), tr_nat])
    chk.check("T2b", f"{name}.translate_aborts_with_v2_message", rc != 0 and v2_msg is not None and v2_msg in err,
              f"rc={rc}; translator: {err[-240:]!r}; v2: {v2_msg!r}"[:600])
    # T2(c): carriers on exactly v2's text-core layers, with v2's z / h / s / F / fu / fp
    blocks, errors = B.parse_records(on)
    chk.check("T2c", f"{name}.records_parse", not errors, f"{len(blocks)} blocks" + (f", errors {errors[:3]}" if errors else ""))
    core, _, _ = v2_text_core(E, kill)
    ks = sorted(b.k for b in blocks)
    chk.check("T2c", f"{name}.carrier_set", ks == sorted(core) and ks,
              f"{len(ks)} carrier(s) on {len(core)} v2 text-core layer(s)")
    fp = B.fingerprint(H._params(E, cfg), E)
    bad = []
    got_begin = begin_lines(on)
    for b in blocks:
        f_c = E.compute_f_powder(P.m_dot, P.rho_tap, P.s_hatch, b.h, P.eta)
        exp = begin_fields(B.write_block(b.k, "open", b.z, b.h, P.s_hatch, f_c, f_c, fp, None).split("\n")[0].strip())
        if b.st != "open" or b.runs or b.fbs or got_begin.get(b.k) != exp or f_c <= P.f_max:
            bad.append(b.k)
    chk.check("T2c", f"{name}.carriers", not bad, f"st=open, s=s_hatch, F=fu=f_calc > f_max, fp equal on all"
              if not bad else f"bad carriers {bad[:10]}")
    # v2's message is the one of the first carrier's layer (same h)
    if blocks:
        b0 = min(blocks, key=lambda b: b.k)
        try:
            E.resolve_powder_feed(P.m_dot, P.rho_tap, P.s_hatch, b0.h, P.eta, P.f_max, P.policy)
            m0 = None
        except E.UMexConfigError as ex:
            m0 = str(ex)
        chk.check("T2c", f"{name}.abort_layer", m0 is not None and m0 == v2_msg, f"first carrier k={b0.k} h={b0.h}")
    # T2(d): offline replay reproduces the keep export
    rdump = os.path.join(sdir, "replay_dump")
    if os.path.isdir(rdump):
        shutil.rmtree(rdump)
    shutil.copytree(dump_dir, rdump)
    rep_out = os.path.join(sdir, "replay.gcode")
    rc, err = run_tr(tr, ["--config-from-gcode", "--plan-records", keep_path, rep_out],
                     {"ORCA_DIW_SHADOW_KEEP_PLACEHOLDERS": "1", "ORCA_DIW_SHADOW_DUMP": rdump})
    same = rc == 0 and os.path.isfile(rep_out) and open(rep_out, "rb").read() == keep
    chk.check("T2d", f"{name}.replay", same, "" if same else (f"rc={rc} {err[-200:]}" if rc else
                                                               first_diff(open(rep_out, "rb").read(), keep)))
    # T2(e) has no output to compare: both sides abort (checked above). Recorded as a deviation.
    info["core"] = (len(ks), len(core))
    info["t2c_layers"] = 0


def scarf_checks(E, sg, shapely, B, H, CP, chk, stats, info, name, sdir, job, ov, stls, args, kill_path, on, tr, tr_nat,
                 dump_dir, warns):
    """T2(c), T3 and T2(e) of a scarf-seam slice. The scarf retraces the outer wall loop with a z ramp, so v2's
    snap + linemerge of the text outer wall no longer forms a ring (v2 gives st=open, or plans without the outer
    ring), while the native ring is the ExtrusionLoop itself. The reference (as T5(iv) for the seam gap) is v2 on the
    same part exported without the scarf (seam_slope_type none, kill switch), with the band model of t5_band_model
    (the reference's outer walls as zero-width ring paths, the scarf text's walls renamed, B_native); T3 is done
    against each block's own planner input text and the native loops; T2(e) diffs translate(on) against the scarf
    kill export carrying v2's reference blocks (placed after the same k's start marker)."""
    import dataclasses
    from compare_powder import parse_config_block, v2_config
    rov = dict(ov)
    rov["seam_slope_type"] = "none"
    settings = write_profiles(os.path.join(sdir, "profiles"), "ref", rov)
    rc, ref, _, _ = slice_part(job["orca"], job["datadir"], stls, os.path.join(sdir, "ref"),
                               dict(job.get("env") or {}, ORCA_DIW_NO_NATIVE_PLAN="1"), settings, args)
    if not chk.check("T2c", f"{name}.ref.rc", rc == 0 and ref is not None, f"rc={rc} (no-scarf reference export)"):
        return
    ref_path = os.path.join(sdir, "ref", "plate_1.gcode")
    kill = open(kill_path, "rb").read()
    cfg = v2_config(parse_config_block(kill), E)
    cfg["enable_u_mex_powder_infill"] = True
    cfg_r = v2_config(parse_config_block(ref), E)
    cfg_r["enable_u_mex_powder_infill"] = True
    v_ref = {L.k: L for L in H.capture_geometry(E, cfg_r, ref_path)}
    v_scarf = {L.k: L for L in H.capture_geometry(E, cfg, kill_path)}
    P = E.UMexParams.from_config(cfg)[0]
    delta = P.delta
    blocks, errors = B.parse_records(on)
    chk.check("T2c", f"{name}.records_parse", not errors, f"{len(blocks)} blocks" + (f", errors {errors[:3]}" if errors else ""))
    nat = {b.k: b for b in blocks}
    core_nat = sorted(nat)
    core_ref = sorted(v_ref)
    core_scarf, _, _ = v2_text_core(E, kill)
    info["core"] = (len(core_nat), len(core_ref))
    # the k set: native = v2's text core of the scarf file = v2's planned layers of the reference
    chk.check("T2c", f"{name}.core_set", core_nat == core_ref == sorted(core_scarf),
              f"{len(core_nat)} native / {len(core_ref)} v2 (no-scarf reference) / {len(core_scarf)} v2 text-core")
    v2_open = [k for k in core_nat if k in v_scarf and v_scarf[k].st == "open"]
    v2_diff = [k for k in core_nat if k in v_scarf and v_scarf[k].st != "open" and k in v_ref and
               abs(v_scarf[k].plan.omega_area - v_ref[k].plan.omega_area) > 1e-3]
    info["v2_scarf"] = (len(v2_open), len(v2_diff), len(core_nat))
    chk.log(f"scarf {name}: v2 on the scarf text gives st=open on {len(v2_open)} and a different Omega on "
            f"{len(v2_diff)} of {len(core_nat)} core layers (the reason for the no-scarf reference)")
    fp = B.fingerprint(H._params(E, cfg_r), E)
    beg = begin_lines(on)
    dumps = load_dumps(dump_dir)
    diffs, n = [], 0
    sub, st_sub = Collector(), new_stats()
    for k in core_nat:
        rec, dj, L = nat[k], dumps.get(k), v_ref.get(k)
        native = (dj or {}).get("native")
        S_nat = native_solid(native, sg)
        loops = native_closed_loops(native, sg)
        if rec.st == "ok":
            if dj is None:
                chk.check("T3", f"{name}.k{k}", False, "no dump for a planned layer")
            else:
                sl, slr, ins = CP.clearance(sg, shapely, dump_text_model(dj), rec.runs, S_nat, delta, loops)
                stats["t3_min"] = min(stats["t3_min"], sl)
                stats["t3_min_rounded"] = min(stats["t3_min_rounded"], slr)
                chk.check("T3", f"{name}.k{k}", sl >= -1e-5 and slr >= 0.0 and ins,
                          f"slack {sl:.3g}, rounded {slr:.3g}, inside S {ins} (own text + native loops)")
        if L is None:
            continue
        g = begin_fields(B.write_block(L.k, L.st, L.z, L.h, L.s, L.F, L.fu, fp, L.plan).split("\n")[0])
        f = beg.get(k)
        for key in ("k", "z", "h", "s", "F", "fu", "fp", "st"):
            if f is None or f[key] != g[key]:
                diffs.append(f"k={k} {key}: native {None if f is None else f[key]} v2 {g[key]}")
        if L.st == "open" and rec.st == "open":
            continue
        if dj is None:
            chk.check("T2c", f"{name}.k{k}.dump", False, "no dump for a planned layer")
            continue
        V = CP.V2Case(f"{name}.k{k}", L.model, L.prm, L.h, L.s, L.z, L.F, L.fu, L.plan, L.geom)
        models = [L.model] + ([v_scarf[k].model] if k in v_scarf else [])
        bm = t5_band_model(E, L.model, v_scarf[k].model, native) if k in v_scarf else None
        compare_t2c(E, sg, shapely, sub, st_sub, V, rec, dj["debug"], native, band_model=bm,
                    mask=seam_discs(models, delta, 0.0, sg), t3_extra=loops, S_native=S_nat)
        n += 1
    for key, v in st_sub.items():
        if key.startswith("t3_"):
            continue
        if key.startswith(("haus", "max_", "fb_pos")):
            stats[key] = max(stats.get(key, 0.0), v)
        else:
            stats[key] = stats.get(key, 0) + v
    for kind, nm, ok, detail in sub.records:
        if kind != "T3":            # T3 is above, against the block's own text
            chk.check(kind, nm, ok, detail)
    chk.logs += sub.logs
    chk.check("T2c", f"{name}.begin", not diffs and bool(beg),
              f"{len(beg)} BEGIN lines string-equal to v2 (no-scarf reference)" if not diffs else "; ".join(diffs[:6]))
    info["t2c_layers"] = n
    # T2(e): the scarf kill export with v2's reference blocks after the same k's start marker
    lines = kill.decode("utf-8", "replace").splitlines(keepends=True)
    starts = {c.index: c.start for c in E.split_layers(lines, E.scan_gcode(lines))}
    moved = [dataclasses.replace(L, start=starts[L.k]) for L in v_ref.values() if L.k in starts]
    v2rec, _ = H.records_from_geometry(E, cfg_r, kill_path, moved)
    v2rec_path = os.path.join(sdir, "v2rec.gcode")
    with open(v2rec_path, "wb") as fh:
        fh.write(v2rec)
    tr_v2 = os.path.join(sdir, "v2rec.translated.gcode")
    rc2, err2 = run_tr(tr, ["--config-from-gcode", v2rec_path, tr_v2])
    if chk.check("T2e", f"{name}.v2_translate", rc2 == 0, f"rc={rc2} {err2[-200:]}" if rc2 else "") and \
            os.path.isfile(tr_nat):
        fb_ks = {k for k, b in nat.items() if b.fbs} | {L.k for L in moved if L.plan is not None and L.plan.fallback_paths}
        run_diff_ks = {L.k for L in moved if L.plan is not None and L.k in nat and len(nat[L.k].runs) != len(L.plan.runs)}
        notes = []
        d = section_diff(norm(open(tr_nat, "rb").read()), norm(open(tr_v2, "rb").read()), fb_ks, run_diff_ks, notes)
        for x in notes:
            chk.log(f"T2e {name}: {x}")
        chk.check("T2e", f"{name}.section_diff", d is None, d or "identical outside S4 bodies and FB lines")


