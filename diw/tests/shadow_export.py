    import v2_hooks as H
    import compare_planner as CP
    from compare_powder import parse_config_block, v2_config
    part, wname, wov = job["part"], job["walls"], job["overrides"]
    name = f"T5.{part}.{wname}"
    chk = Collector()
    stats = new_stats()
    info = {"name": name}
    t0 = time.time()
    try:
        E, sg, shapely = _engine(job["engine"])
        sdir = os.path.join(job["work"], "t5", f"{part}.{wname}")
        os.makedirs(sdir, exist_ok=True)
        stls, args = mesh_files(job["mdir"], part)
        res = {}
        for tag, gap in (("gap0", "0%"), ("gap15", T5_GAP)):
            ov = dict(wov)
            ov["seam_gap"] = gap
            settings = write_profiles(os.path.join(sdir, "profiles"), tag, ov)
            dd = os.path.join(sdir, tag + ".dump")
            if os.path.isdir(dd):
                shutil.rmtree(dd)
            os.makedirs(dd)
            od = os.path.join(sdir, tag)
            # a DIW printer forces seam_gap to 0 (PrintApply.cpp apply_diw_overrides) and Print::validate refuses a
            # per-object seam gap; the test-only ORCA_DIW_TEST_KEEP_SEAM_GAP=1 keeps it (a no-op at 0 %)
            rc, data, log, _ = slice_part(job["orca"], job["datadir"], stls, od,
                                          {"ORCA_DIW_SHADOW_DUMP": dd, "ORCA_DIW_TEST_KEEP_SEAM_GAP": "1"}, settings, args)
            if not chk.check("T5", f"{name}.{tag}.rc", rc == 0 and data is not None, f"rc={rc}"):
                continue
            cb = parse_config_block(data)
            chk.check("T5", f"{name}.{tag}.settings", str(cb.get("seam_gap", "")).strip() == gap,
                      f"seam_gap {cb.get('seam_gap')!r}")
            summ = parse_summary(log)
            badr = {r: n for r, n in summ["reasons"].items() if r in BAD_REASONS and n} if summ else None
            chk.check("T5ii", f"{name}.{tag}.summary_clean", summ is not None and not badr and not summ["disabled"]
                      and summ["max_held"] <= 1, f"summary {summ}")
            res[tag] = (data, os.path.join(od, "plate_1.gcode"), load_dumps(dd), cb)
        if len(res) != 2:
            return {"name": name, "records": chk.records, "logs": chk.logs, "stats": stats, "info": info}
        (on0, path0, dumps0, cb0), (on15, path15, dumps15, cb15) = res["gap0"], res["gap15"]
        gap_mm = 0.15 * float(str(cb15.get("nozzle_diameter", "0")).split(",")[0])
        info["gap_mm"] = gap_mm
        chk.check("T5", f"{name}.gap", gap_mm > E.LOOP_CLOSE_TOL_MM,
                  f"seam gap {gap_mm:.3f} mm > LOOP_CLOSE_TOL {E.LOOP_CLOSE_TOL_MM} mm")

        # ---- (v) the translator accepts both files (powder mode)
        for tag, p in (("gap0", path0), ("gap15", path15)):
            out = os.path.join(sdir, f"{tag}.translated.gcode")
            rc, err = run_tr(job["translate"], ["--config-from-gcode", p, out])
            chk.check("T5v", f"{name}.{tag}.translate", rc == 0 and os.path.isfile(out), f"rc={rc} {err[-300:]}" if rc else "rc=0")

        # ---- v2 on both texts
        def v2_layers(tag, data):
            src = os.path.join(sdir, f"{tag}.stripped.gcode")
            with open(src, "wb") as fh:
                fh.write(strip_records(data))
            cfg = v2_config(parse_config_block(data), E)
            cfg["enable_u_mex_powder_infill"] = True
            try:
                return {L.k: L for L in H.capture_geometry(E, cfg, src)}, cfg, None
            except Exception as ex:      # v2 refusing the whole file is "no plan" on every layer
                return {}, cfg, f"{type(ex).__name__}: {str(ex)[:200]}"
        v0, cfg0, err0 = v2_layers("gap0", on0)
        v15, cfg15, err15 = v2_layers("gap15", on15)
        chk.check("T5iv", f"{name}.v2_gap0", err0 is None and bool(v0), err0 or f"{len(v0)} v2 layers")
        P = E.UMexParams.from_config(cfg15)[0]
        delta = P.delta

        def parsed(data, tag):
            blocks, errors = B.parse_records(data)
            chk.check("T5", f"{name}.{tag}.records_parse", not errors and bool(blocks),
                      f"{len(blocks)} blocks" + (f", errors {errors[:3]}" if errors else ""))
            nat = {b.k: b for b in blocks}
            carriers = {b.k for b in blocks if b.st == "open" and (b.h <= 0.0 or (P.policy == "error" and b.F == b.fu))}
            return nat, sorted(k for k in nat if k not in carriers)
        nat0, core0 = parsed(on0, "gap0")
        nat15, core15 = parsed(on15, "gap15")
        info["core"] = (len(core15), len(core0))

        # ---- (i) v2 really fails at 15 %
        v2_open = [k for k in core0 if k in v15 and v15[k].st == "open"]
        v2_none = [k for k in core0 if k not in v15]
        v2_ok = [k for k in core0 if k in v15 and v15[k].st != "open"]
        info["v2_15"] = (len(v2_open), len(v2_none), len(v2_ok), len(core0))
        chk.check("T5i", f"{name}.v2_fails", bool(v2_open or v2_none),
                  f"v2 at seam_gap {T5_GAP}: st=open on {len(v2_open)}, no plan on {len(v2_none)}, planned on "
                  f"{len(v2_ok)} of {len(core0)} core layers" + (f"; v2 raised {err15}" if err15 else ""))
        if v2_ok:
            chk.log(f"T5i {name}: v2 at {T5_GAP} still plans layers {v2_ok}")

        # ---- (ii) native still plans every core layer, same k set as at 0 %
        bad_st = {k: nat15[k].st for k in core15 if nat15[k].st not in ("ok", "small")}
        chk.check("T5ii", f"{name}.native_st", not bad_st and bool(core15),
                  f"{len(core15)} core layers, st " + str({s: sum(1 for k in core15 if nat15[k].st == s)
                                                           for s in sorted({nat15[k].st for k in core15})})
                  + (f"; not ok/small {bad_st}" if bad_st else ""))
        chk.check("T5ii", f"{name}.core_set", core15 == core0,
                  f"{len(core15)} core layers at {T5_GAP} / {len(core0)} at 0 %" +
                  ("" if core15 == core0 else f"; only 15 % {sorted(set(core15) - set(core0))}, "
                                              f"only 0 % {sorted(set(core0) - set(core15))}"))

        # ---- (iii) reported metric: native 15 % vs native 0 %
        rows, inputs = [], {"paste": [], "sparse": [], "chunking": [], "h_s": [], "walls": [], "open_outer": []}
        beg0, beg15 = begin_lines(on0), begin_lines(on15)
        for k in sorted(set(core0) & set(core15)):
            a, b = nat0[k], nat15[k]
            d0, d1 = dumps0.get(k), dumps15.get(k)
            if any(beg0[k][x] != beg15[k][x] for x in ("z", "h")) if k in beg0 and k in beg15 else True:
                inputs["chunking"].append(k)
            if d0 is None or d1 is None:
                continue
            i0, i1 = d0["input"], d1["input"]
            if i0.get("text_paste") != i1.get("text_paste"):
                inputs["paste"].append(k)
            if i0.get("text_powder") != i1.get("text_powder"):
                inputs["sparse"].append(k)
            if (i0.get("h"), i0.get("s_eff")) != (i1.get("h"), i1.get("s_eff")):
                inputs["h_s"].append(k)
            if i0.get("text_walls") != i1.get("text_walls"):
                inputs["walls"].append(k)
            if len(i1.get("open_outer", [])) != len(i0.get("open_outer", [])):
                inputs["open_outer"].append(k)
            if a.st != "ok" or b.st != "ok":
                continue

            def rel(x, y):
                return abs(x - y) / abs(y) if y else abs(x - y)
            O0, O1 = shapely.from_wkt(d0["debug"]["omega"]), shapely.from_wkt(d1["debug"]["omega"])
            hO = CP.hausdorff(O0.boundary, O1.boundary, sg)
            hR = CP.hausdorff(CP.runs_geom(a.runs, sg), CP.runs_geom(b.runs, sg), sg)
            p0 = [r.pts[0] for r in a.runs if r.kind == "point"]
            p1 = [r.pts[0] for r in b.runs if r.kind == "point"]
            hP = max((math.hypot(x[0] - y[0], x[1] - y[1]) for x, y in zip(p0, p1)), default=0.0) \
                if len(p0) == len(p1) else math.inf
            rows.append((k, rel(b.ca, a.ca), rel(b.oa, a.oa), rel(b.ra, a.ra), abs(b.ra - a.ra), hO, max(hR, hP),
                         len(a.runs) == len(b.runs), a.nc == b.nc))
        if rows:
            worst = (max(r[1] for r in rows), max(r[2] for r in rows), max(r[3] for r in rows), max(r[4] for r in rows),
                     max(r[5] for r in rows), max(r[6] for r in rows))
            within = all(r[1] <= 1e-6 and r[2] <= 1e-6 and (r[3] <= 1e-6 or r[4] <= 1e-9) and r[5] <= 0.5 * UM
                         and r[6] <= 0.5 * UM and r[7] and r[8] for r in rows)
        else:
            worst, within = None, None
        info["t5iii"] = {"layers": len(rows), "worst": worst, "within_expected": within,
                         "inputs_changed": {k: v for k, v in inputs.items() if v},
                         "over": [r for r in rows if not (r[1] <= 1e-6 and r[2] <= 1e-6 and (r[3] <= 1e-6 or r[4] <= 1e-9)
                                                          and r[5] <= 0.5 * UM and r[6] <= 0.5 * UM and r[7] and r[8])][:8]}

        # ---- (iv) native 15 % vs v2 0 % with the T2(c) tolerances; (v) T3 on the 15 % text
        diffs, n_iv = [], 0
        fp = B.fingerprint(H._params(E, cfg0), E)
        sub = Collector()
        st_iv = new_stats()          # its T3 minima belong to the 0 % text and are not reported
        for k in core15:
            rec, dj = nat15[k], dumps15.get(k)
            native = (dj or {}).get("native")
            S_nat = native_solid(native, sg)
            loops = native_closed_loops(native, sg)
            if rec.st == "ok":
                if dj is None:
                    chk.check("T5v", f"{name}.k{k}.T3", False, "no dump for a planned layer")
                else:
                    sl, slr, ins = CP.clearance(sg, shapely, dump_text_model(dj), rec.runs, S_nat, delta, loops)
                    stats["t3_min"] = min(stats["t3_min"], sl)
                    stats["t3_min_rounded"] = min(stats["t3_min_rounded"], slr)
                    chk.check("T5v", f"{name}.k{k}.T3", sl >= -1e-5 and slr >= 0.0 and ins,
                              f"slack {sl:.3g}, rounded {slr:.3g}, inside S {ins} (15 % text + native loops)")
            L = v0.get(k)
            if L is None:
                chk.check("T5iv", f"{name}.k{k}", False, "no v2 layer at seam_gap 0 %")
                continue
            g = begin_fields(B.write_block(L.k, L.st, L.z, L.h, L.s, L.F, L.fu, fp, L.plan).split("\n")[0])
            f = beg15.get(k)
            for key in ("k", "z", "h", "s", "F", "fu", "fp", "st"):
                if f is None or f[key] != g[key]:
                    diffs.append(f"k={k} {key}: native {None if f is None else f[key]} v2 {g[key]}")
            if L.st == "open" and rec.st == "open":
                continue
            if dj is None:
                chk.check("T5iv", f"{name}.k{k}.dump", False, "no dump for a planned layer")
                continue
            V = CP.V2Case(f"{name}.k{k}", L.model, L.prm, L.h, L.s, L.z, L.F, L.fu, L.plan, L.geom)
            models = [L.model] + ([v15[k].model] if k in v15 else [])
            bm = t5_band_model(E, L.model, v15[k].model, native) if k in v15 else None
            compare_t2c(E, sg, shapely, sub, st_iv, V, rec, dj["debug"], native, band_model=bm,
                        mask=seam_discs(models, delta, gap_mm, sg), t3_extra=loops, S_native=S_nat)
            n_iv += 1
        # T3 of these blocks is T5(v), against their own (15 %) text; compare_case's T3 against the 0 % text is not
        # the invariant (that file's rounded seam vertices are not obstacles of this one) and is left out
        for key, v in st_iv.items():
            if key.startswith("t3_"):
                continue
            if key.startswith(("haus", "max_", "fb_pos")):
                stats[key] = max(stats.get(key, 0.0), v)
            else:
                stats[key] = stats.get(key, 0) + v
        for kind, nm, ok, detail in sub.records:
            if kind != "T3":
                chk.check(f"T5iv.{kind}", nm, ok, detail)
        chk.logs += sub.logs
        chk.check("T5iv", f"{name}.begin", not diffs and bool(beg15),
                  f"{len(beg15)} BEGIN lines string-equal to v2 at 0 %" if not diffs else "; ".join(diffs[:6]))
        info["t5iv_layers"] = n_iv
    except Exception as ex:  # a harness error is a failure, never a skip
        import traceback
        chk.check("error", name, False, f"{type(ex).__name__}: {ex} | {traceback.format_exc()[-600:]}")
    info["seconds"] = time.time() - t0
    return {"name": name, "records": chk.records, "logs": chk.logs, "stats": stats, "info": info}


