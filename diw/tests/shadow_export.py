def t10(rep, orca, datadir, mdir, work):
    """T10: the CLI export (slicing + G-code export, the command a user runs) with the shadow on takes <= 1.2 x the
    kill-switch time, best of T10_RUNS alternating runs each; the G-code export step alone (GCode::do_export,
    logged as export_ms) is reported beside it. Every shadow export holds at most one chunk (max_held == 1)."""
    for part in T10_PARTS:
        stls, args = mesh_files(mdir, part)
        times = {"kill": [], "on": []}
        exp = {"kill": [], "on": []}
        held, binder = [], []
        for it in range(T10_RUNS):
            for rn, env in (("kill", {"ORCA_DIW_NO_NATIVE_PLAN": "1"}), ("on", {})):
                rc, data, log, dt = slice_part(orca, datadir, stls, os.path.join(work, "t10", f"{part}.{rn}"), env, None, args)
                if rc == 0 and data is not None:
                    times[rn].append(dt)
                m = EXPORT_MS_RE.search(log)
                if m:
                    exp[rn].append(float(m.group(1)))
                if rn == "on":
                    s = parse_summary(log)
                    held.append(s["max_held"] if s else -1)
                    if s:
                        binder.append(s["binder_ms"] + s["capture_ms"])
        ok = len(times["kill"]) == T10_RUNS and len(times["on"]) == T10_RUNS
        ratio = min(times["on"]) / min(times["kill"]) if ok else math.inf
        eratio = min(exp["on"]) / min(exp["kill"]) if exp["on"] and exp["kill"] else math.inf
        rep.check(f"T10.{part}.time", ok and ratio <= 1.2,
                  f"CLI export on {min(times['on']) if times['on'] else 0:.3f} s / kill "
                  f"{min(times['kill']) if times['kill'] else 0:.3f} s = {ratio:.3f} (best of {T10_RUNS}); "
                  f"G-code export step alone {min(exp['on']) if exp['on'] else 0:.1f} / "
                  f"{min(exp['kill']) if exp['kill'] else 0:.1f} ms = {eratio:.2f}; planner (capture + binder) "
                  f"{min(binder) if binder else 0:.1f} ms")
        rep.check(f"T10.{part}.max_held", held and all(h == 1 for h in held), f"max_held per export {held}")


