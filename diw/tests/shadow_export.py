# ----------------------------------------------------------------------------- T2(e) section-aware diff

HDR_RE = re.compile(rb"^; --- uMEX L(\d+) S(\d)")
MOVE_RE = re.compile(rb"^G[01] ")


def sections(data):
    """[(key, [lines])]: key None before the first uMEX header, else (k, stage) of the header that opens it."""
    out = [(None, [])]
    for l in data.splitlines(keepends=True):
        m = HDR_RE.match(l)
        if m:
            out.append(((int(m.group(1)), int(m.group(2))), [l]))
        else:
            out[-1][1].append(l)
    return out


RUN_WARN_RE = re.compile(rb"^; WARNING \(uMEX\): \d+ powder run\(s\) in layers ")


def section_diff(a, b, fb_ks, run_diff_ks=(), notes=None):
    """None when a and b are byte-identical outside the S4 bodies and the fallback lines of S1 (layers in fb_ks
    whose S1 sections may differ by a run of G0 / G1 lines between a common prefix and suffix); else a message.
    With run_diff_ks, the header's powder run-length warning lines (a summary of the S4 bodies) may differ too."""
    notes = [] if notes is None else notes
    sa, sb = sections(a), sections(b)
    if [k for k, _ in sa] != [k for k, _ in sb]:
        ka, kb = [k for k, _ in sa], [k for k, _ in sb]
        i = next((i for i, (x, y) in enumerate(zip(ka, kb)) if x != y), min(len(ka), len(kb)))
        return f"section sequence differs at #{i}: {ka[i:i + 2]} vs {kb[i:i + 2]} ({len(ka)} vs {len(kb)} sections)"
    n_fb = 0
    for (key, la), (_, lb) in zip(sa, sb):
        if key is not None and key[1] == 4:
            if la[0] != lb[0]:
                return f"S4 header L{key[0]}: {la[0][:90]!r} vs {lb[0][:90]!r}"
            continue
        if la == lb:
            continue
        if key is None and run_diff_ks:
            # the header's "; WARNING (uMEX): <n> powder run(s) in layers ..." lines summarize the S4 run lengths,
            # so they follow a run set that T2(c) accepted as different (run_diff_ks: layers whose native and v2
            # run counts differ); everything else in the header must still be identical
            fa = [l for l in la if not RUN_WARN_RE.match(l)]
            fb = [l for l in lb if not RUN_WARN_RE.match(l)]
            if fa == fb:
                notes.append(f"header run-length warning follows the run sets of layers {sorted(run_diff_ks)}")
                continue
        if key is not None and key[1] == 1 and key[0] in fb_ks:
            i = 0
            while i < min(len(la), len(lb)) and la[i] == lb[i]:
                i += 1
            j = 0
            while j < min(len(la), len(lb)) - i and la[-1 - j] == lb[-1 - j]:
                j += 1
            mid_a, mid_b = la[i:len(la) - j], lb[i:len(lb) - j]
            if all(MOVE_RE.match(l) for l in mid_a + mid_b):
                n_fb += 1
                continue
            bad = next((l for l in mid_a + mid_b if not MOVE_RE.match(l)), b"")
            return f"S1 L{key[0]}: non-motion line differs: {bad[:90]!r}"
        d = first_diff(b"".join(la), b"".join(lb))
        return f"section {key}: {d}"
    return None


# ----------------------------------------------------------------------------- geometry helpers

def nm_ring(pts):
    return [(int(x) * 1e-6, int(y) * 1e-6) for x, y in pts]


def native_solid(native, sg):
    """The EvenOdd union of the native rings (mm), or None."""
    if not native:
        return None
    S = sg.Polygon()
    for inst in native.get("rings", []):
        for r in inst:
            pts = nm_ring(r)
            if len(pts) >= 3:
                S = S.symmetric_difference(sg.Polygon(pts).buffer(0))
    return None if S.is_empty else S


def native_closed_loops(native, sg):
    out = []
    for w in (native or {}).get("pieces", []):
        pts = nm_ring(w["pts"])
        if w.get("closed") and len(pts) >= 2:
            out.append((float(w["width"]), sg.LineString(pts + [pts[0]])))
    return out


def seam_mask(model, delta, gap, sg):
    discs = []
    for p in model.paths:
        if p.kind == "wall" and p.ptype == "outer wall" and p.points:
            discs.append(sg.Point(p.points[0]).buffer(p.width + delta + gap, quad_segs=16))
    return sg.unary_union(discs) if discs else None


def native_band_model(E, model, native):
    """A copy of v2's LayerModel with the native wall pieces added as wall paths of ptype "native wall": v2's band is
    then B_text U B_native, the band the native planner uses (section 7.2 P2). The rings (outer / overhang walls)
    are unchanged."""
    import copy
    m = copy.copy(model)
    m.paths = list(model.paths)
    z = next((p.z for p in model.paths if p.kind == "wall"), 0.0)
    for w in (native or {}).get("pieces", []):
        pts = nm_ring(w["pts"])
        if w.get("closed") and len(pts) > 2:
            pts = pts + [pts[0]]
        if len(pts) < 2:
            continue
        m.paths.append(E.PathRec(ptype="native wall", kind="wall", points=pts, seg_de=[0.0] * (len(pts) - 1),
                                 seg_feed=[0.0] * (len(pts) - 1), seg_raw=[], width=float(w["width"]), z=z,
                                 pre_lines=[], travel_feed=None))
    return m


T2C_KINDS = ("st_nc", "areas", "shape", "hatch", "fb")

# Review fix 4: the native pieces that a reference candidate adds to v2's band are first checked against the printed
# text, independently of the capture: every piece segment must lie on a text wall segment (within the frame
# tolerance) whose own ;WIDTH: equals the piece width. Only the seam tail of a closed loop (clip_end; the seam gap)
# may be unprinted.
VERIFY_TOL = 1e-3 * math.sqrt(2) + 1e-6      # gate 9's frame tolerance at 3 decimals
VERIFY_WTOL = 5e-6                            # ;WIDTH: is printed with 6 significant digits


def text_wall_segments(model):
    """[(a, b, width)] of every wall segment of a v2 LayerModel with its own ;WIDTH: (v2_hooks.seg_width_model
    annotates the per-segment widths; without them the path's first-segment width)."""
    sw = getattr(model, "path_seg_width", None) or {}
    out = []
    for i, p in enumerate(model.paths):
        if p.kind != "wall" or len(p.points) < 2:
            continue
        ws = sw.get(i) or [p.width] * (len(p.points) - 1)
        for (a, b), w in zip(zip(p.points, p.points[1:]), ws):
            out.append((a, b, float(w)))
    return out


def verify_native_pieces(native, model, gap=0.0):
    """(ok, message, wider): checks every native wall piece against the printed text walls (see VERIFY_TOL).
    wider: some piece is wider than the first-segment width of the text path it is printed as (the D2 situation)."""
    import numpy as np
    segs = text_wall_segments(model)
    pieces = (native or {}).get("pieces", [])
    if not pieces:
        return False, "no native pieces", False
    if not segs:
        return False, "no text wall segments", False
    A = np.array([s[0] for s in segs], dtype=float)
    Bv = np.array([s[1] for s in segs], dtype=float)
    W = np.array([s[2] for s in segs], dtype=float)
    first = {}
    for p in model.paths:
        if p.kind == "wall" and len(p.points) >= 2:
            for a, b in zip(p.points, p.points[1:]):
                first[(a, b)] = float(p.width)
    D = Bv - A
    L2 = np.maximum((D * D).sum(1), 1e-30)
    tot_len = bad_len = 0.0
    wider = False
    worst = []
    for w in pieces:
        pts = nm_ring(w["pts"])
        if w.get("closed") and len(pts) > 2:
            pts = pts + [pts[0]]
        wn = float(w["width"])
        unmatched = 0.0
        for a, b in zip(pts, pts[1:]):
            ln = math.hypot(b[0] - a[0], b[1] - a[1])
            if ln <= 0.0:
                continue
            tot_len += ln
            m = np.array([(a[0] + b[0]) / 2.0, (a[1] + b[1]) / 2.0])
            t = np.clip(((m - A) * D).sum(1) / L2, 0.0, 1.0)
            dist = np.hypot(*(A + t[:, None] * D - m).T)
            near = dist <= VERIFY_TOL
            same_w = near & (np.abs(W - wn) <= VERIFY_WTOL + 1e-5 * wn)
            if not same_w.any():
                unmatched += ln
                if near.any() and len(worst) < 3:
                    worst.append(f"width {wn!r} vs text {sorted(set(float(x) for x in W[near]))[:3]}")
                continue
            j = int(np.flatnonzero(same_w)[0])
            if wn > first.get((tuple(A[j]), tuple(Bv[j])), wn) + VERIFY_WTOL:
                wider = True
        allow = 2.0 * wn + gap + 0.1          # the seam tail of a closed loop is not printed
        if unmatched > allow + 1e-9:
            bad_len += unmatched
    ok = tot_len > 0.0 and bad_len <= 0.0
    msg = (f"native pieces vs printed text walls: {bad_len:.3g} of {tot_len:.3g} mm unmatched beyond the seam allowance"
           + (f" ({'; '.join(worst)})" if worst else ""))
    return ok, msg, wider


def self_check_hatch_fb(E, sg, shapely, V, rec, dbg):
    """Review fix 6: on a layer where v2's Omega is ill-conditioned, the native hatch and fallback paths are checked
    against v2's own algorithms run on the native geometry: hatch_polygon on each native Omega component (point
    dwell at its centroid with v2's mass formula), and v2's fallback clip of the text sparse infill by the native
    revert. {kind: (ok, detail)} for "hatch" and "fb"."""
    import compare_planner as CP
    import v2_blocks as B
    out = {}
    On = shapely.from_wkt(dbg["omega"])
    polys = sorted(CP._polys(On), key=lambda g: (round(g.bounds[1], 6), round(g.bounds[0], 6)))
    prm, s = V.prm, V.s
    runs, probs = [], []
    comps = []
    for poly in polys:
        rr = E.hatch_polygon(poly, s, prm.hatch_angle, sg)
        total = sum(E.PowderRun(r).length for r in rr)
        if total < prm.point_len:
            c = poly.centroid
            if not poly.contains(c):
                c = poly.representative_point()
            m_target = poly.area * V.h * 1e-3 * prm.rho_tap * prm.eta
            comps.append(("point", [B.RunRec("point", [(c.x, c.y)], None)], 60.0 * m_target / prm.m_dot))
        else:
            comps.append(("line", [B.RunRec("line", list(r), None) for r in rr], None))
    n_exp = sum(len(c[1]) for c in comps)
    if n_exp != len(rec.runs):
        probs.append(f"run count native {len(rec.runs)} vs v2 hatch of native Omega {n_exp}")
    else:
        i = 0
        for kind, rr, d in comps:
            mine = rec.runs[i:i + len(rr)]
            i += len(rr)
            if kind == "point":
                a, b = mine[0], rr[0]
                dp = math.hypot(a.pts[0][0] - b.pts[0][0], a.pts[0][1] - b.pts[0][1])
                if a.kind != "point" or dp > CP.HAUS or abs(a.d - d) > 1e-6 * d:
                    probs.append(f"point dwell pos {dp:.3g} d {a.d!r} vs {d!r}")
            else:
                if any(r.kind != "line" for r in mine):
                    probs.append("point dwell where v2 hatches")
                    continue
                hr = CP.hausdorff(CP.runs_geom(mine, sg), CP.runs_geom(rr, sg), sg)
                if hr > CP.HAUS:
                    probs.append(f"runs Hausdorff {hr:.3g} vs v2 hatch of native Omega")
    out["hatch"] = (not probs, "self-check: " + "; ".join(probs[:3]))
    # fallback paths: v2's clip of the text sparse infill by the native revert (v2 plan_powder_layer, verbatim)
    revert = CP._polys(shapely.from_wkt(dbg["revert"]))
    fbs = []
    if revert and rec.runs:
        pad = min(0.5 * prm.width_fallback, 0.5 * prm.delta)
        clip = sg.unary_union([g.buffer(pad, quad_segs=E.UMEX_QUAD_SEGS) for g in revert])
        for p in V.model.paths:
            if p.kind != "powder":
                continue
            cur_pts, cur_de, cur_feed = [], [], []
            for a, b, de, fd in zip(p.points, p.points[1:], p.seg_de, p.seg_feed):
                seg = sg.LineString([a, b])
                if seg.length < 1e-9:
                    continue
                for piece in E._flat(seg.intersection(clip), ("LineString",)):
                    c = list(piece.coords)
                    if piece.length < 0.05:
                        continue
                    if not (cur_pts and math.hypot(c[0][0] - cur_pts[-1][0], c[0][1] - cur_pts[-1][1]) < 1e-6):
                        if cur_pts:
                            fbs.append(E._synthetic_path(p, cur_pts, cur_de, cur_feed))
                        cur_pts, cur_de, cur_feed = [c[0]], [], []
                    cur_pts.append(c[-1])
                    cur_de.append(de * piece.length / seg.length)
                    cur_feed.append(fd)
            if cur_pts and cur_de:
                fbs.append(E._synthetic_path(p, cur_pts, cur_de, cur_feed))
    import types
    t = Collector()
    CP.compare_fb(t, new_stats(), V.name + "#self", rec, types.SimpleNamespace(fallback_paths=fbs))
    bad = [d for k, n, ok, d in t.records if not ok]
    out["fb"] = (not bad, "self-check: " + "; ".join(bad))
    return out


def compare_t2c(E, sg, shapely, chk, stats, V, rec, dbg, native, **kw):
    """compare_planner.compare_arbitrated of a native block against v2. When it fails, v2 is run again with the
    native wall pieces added to its band (D2: the native band is B_native U B_text, so where the native walls are
    wider than v2's first-segment ;WIDTH: - Arachne - v2's own plan of that band is the reference); if every check
    passes there, the difference is the intended band divergence and is logged, not failed."""
    import compare_planner as CP
    import v2_hooks as H
    band_model = kw.pop("band_model", None)
    seam_gap = kw.pop("seam_gap", 0.0)
    tmp = Collector()
    # review fix 8: the first comparison's statistics are kept apart and only reported when it is the accepted one
    first = new_stats()
    CP.compare_arbitrated(E, sg, shapely, tmp, first, V, rec, dbg, **kw)
    failed = [r for r in tmp.records if not r[2] and r[0] in T2C_KINDS]

    def v2_case(model, q, tag):
        old = E.UMEX_QUAD_SEGS
        try:
            E.UMEX_QUAD_SEGS = q
            plan = E.plan_powder_layer(model, V.prm, V.h, V.s, sg)
            geom = H.v2_geometry(E, model, V.prm, sg)
        finally:
            E.UMEX_QUAD_SEGS = old
        return CP.V2Case(f"{V.name}+{tag}q{q}", model, V.prm, V.h, V.s, V.z, V.F, V.fu, plan, geom)

    def passes(Vc):
        t = Collector()
        st = new_stats()
        CP.compare_arbitrated(E, sg, shapely, t, st, Vc, rec, dbg, **kw)
        return (t, st) if not any(not r[2] for r in t.records) else None

    if failed:
        models = [("", V.model)]
        # review fix 4: the native pieces only enter a reference after they are verified against the printed text
        # walls (positions and per-segment ;WIDTH:), so a capture error cannot copy itself into the reference. A
        # verified native band differs from v2's where a piece is wider than its text path's first-segment width
        # (Arachne) and where a closed loop covers its unprinted seam tail (classic too); `wider` tells them apart in
        # the statistics (d2_wider / d2_seam_tail).
        vok, wider = True, False
        if native and native.get("pieces"):
            vok, vmsg, wider = verify_native_pieces(native, V.model, seam_gap)
            if not vok:
                chk.log(f"native band candidates refused {V.name}: {vmsg}")
                stats["native_pieces_unverified"] = stats.get("native_pieces_unverified", 0) + 1
            else:
                models.insert(0, ("native_band", native_band_model(E, V.model, native)))
        if band_model is not None and vok:
            # T5(iv): v2 on the band the native planner used for this block (another file's text + B_native)
            models.insert(0, ("seam_band", band_model))
        # D2: v2 run on B_text U B_native (the band the native planner uses)
        cands = [(tag, m, E.UMEX_QUAD_SEGS) for tag, m in models if tag]
        # ill-conditioned Omega: v2's own Omega moves by more than the 2 um tolerance between its arc
        # discretizations (a neck of near-zero width opens or closes); native is then judged against v2 at each
        # discretization of RA_QUADS and accepted when it matches one of them
        base_O = V.geom["omega"] if V.geom else None
        spread = 0.0
        if base_O is not None:
            for q in CP.RA_QUADS[1:]:
                Vq = v2_case(V.model, q, "spread")
                if Vq.geom is not None:
                    spread = max(spread, CP.hausdorff(base_O.boundary, Vq.geom["omega"].boundary, sg))
        if spread > CP.HAUS:
            cands += [(tag, m, q) for tag, m in models for q in CP.RA_QUADS]
        else:
            # v2's own arc discretization beyond compare_arbitrated's quad_segs 256: v2 run with finer arcs than its
            # default converges to the native result (e.g. a hatch run that v2 splits at a chord vertex of its Omega
            # boundary up to quad_segs 512 and joins at 1024)
            cands += [(tag, m, q) for tag, m in reversed(models) for q in CP.RA_QUADS if q > E.UMEX_QUAD_SEGS]
        for tag, m, q in cands:
            t = passes(v2_case(m, q, tag))
            if t is None:
                continue
            fine = not tag and spread <= CP.HAUS
            why = ("T5 seam-gap text band" if tag == "seam_band" else "D2 native band" if tag else
                   ("v2 fine discretization" if fine else "v2 Omega ill-conditioned")) + \
                  (f" (v2 Omega spread {spread:.3g} mm over quad_segs {CP.RA_QUADS})" if spread > CP.HAUS else "")
            t, t_stats = t
            for kind, name, ok, detail in failed:
                chk.log(f"{why} {kind} {name}: [{detail}]; within tolerance of v2" +
                        (" run on the 15 % text (S of the 0 % rings) U B_native" if tag == "seam_band" else
                         (" run on B_text U B_native" if tag else "")) + f" at quad_segs={q}")
            CP.merge_stats(stats, t_stats)
            key = "v2_fine_quad" if fine else ("d2_native_band" if tag and spread <= CP.HAUS else "omega_illcond")
            if tag == "seam_band":
                key = "t5_seam_band"
            stats[key] = stats.get(key, 0) + 1
            if tag == "native_band":
                k2 = "d2_wider" if wider else "d2_seam_tail"
                stats[k2] = stats.get(k2, 0) + 1
            for r in t.records:
                chk.check(*r)
            chk.logs += t.logs
            return
        if spread > CP.HAUS and all(r[0] in ("areas", "shape", "hatch", "fb") for r in failed):
            # v2 does not resolve this Omega (its quad_segs variants differ by more than the tolerance and none
            # matches): the native Omega is judged against the exact definition instead - every boundary point
            # (densified to 0.05 mm) keeps the exact clearance d_eff - 10 nm from every wall / paste band and from
            # the boundary of S, oa lies inside v2's own spread over RA_QUADS, and ca matches v2 at one of them.
            import numpy as np
            On = shapely.from_wkt(dbg["omega"])
            d_eff = V.prm.delta + CP.GUARD
            pts = []
            for poly in CP._polys(On):
                for ring in [poly.exterior] + list(poly.interiors):
                    dense = shapely.segmentize(ring, 0.05)
                    pts += list(dense.coords)
            obst = [(p.width, sg.LineString(p.points)) for p in V.model.paths
                    if p.kind in ("wall", "paste") and len(p.points) >= 2] + list(kw.get("t3_extra") or [])
            S = kw.get("S_native") or V.geom["solid"]

            def exact_slack(pp):
                P_ = shapely.points(np.array(pp))
                sl = np.full(len(pp), np.inf)
                for w, line in obst:
                    sl = np.minimum(sl, shapely.distance(P_, line) - w / 2.0 - d_eff)
                return np.minimum(sl, shapely.distance(P_, S.boundary) - d_eff)
            slack = exact_slack(pts) if pts else np.array([])
            sound = len(pts) > 0 and float(slack.min()) >= -1e-5
            # Native Omega outside v2's (+0.3 um): where the native boundary along it is tight (exact slack <= 2 um,
            # the T1 shape tolerance) the excess is v2's own under-approximation of the exact Omega - an edge that
            # ends on a chord vertex of a quad_segs arc short of the exact corner, so it is tilted by up to 2 um over
            # its length. That area is not counted against oa.
            excess, excess_ok, worst = 0.0, True, 0.0
            if sound:
                ex = On.difference(V.geom["omega"].buffer(CP.CONTAIN, quad_segs=32))
                rings = [r for poly in CP._polys(On) for r in [poly.exterior] + list(poly.interiors)]
                for g in CP._polys(ex):
                    if g.area <= 1e-9:
                        continue
                    near = g.buffer(0.5 * UM)
                    bp = [c for r in rings for c in shapely.segmentize(r, 0.01).coords if near.contains(sg.Point(c))]
                    m = float(exact_slack(bp).max()) if bp else math.inf
                    worst = max(worst, m)
                    excess_ok = excess_ok and m <= CP.HAUS + 1e-5
                    excess += g.area
            oas, cas = [], []
            for q in CP.RA_QUADS:
                Vq = v2_case(V.model, q, "exact")
                if Vq.plan is not None:
                    oas.append(Vq.plan.omega_area)
                    cas.append(Vq.plan.cavity_area)
            tol_oa = 1e-5 * max(oas) + 1e-4 if oas else 0.0
            oa_ok = bool(oas) and min(oas) - tol_oa <= rec.oa <= max(oas) + tol_oa
            oa_tight = not oa_ok and bool(oas) and excess_ok and excess > 0.0 and \
                min(oas) - tol_oa <= rec.oa - excess <= max(oas) + tol_oa
            ca_ok = any(abs(rec.ca - c) <= 1e-5 * c + 1e-4 for c in cas)
            if sound and (oa_ok or oa_tight) and ca_ok:
                for kind, name, ok, detail in failed:
                    chk.log(f"v2 Omega ill-conditioned {kind} {name}: [{detail}]; v2 Omega spread {spread:.3g} mm over "
                            f"quad_segs {CP.RA_QUADS} (oa {min(oas):.6f}..{max(oas):.6f}); native Omega keeps the exact "
                            f"clearance (min slack {float(slack.min()):.3g} mm), oa {rec.oa:.6f} inside v2's spread" +
                            (f" once the tight excess over v2 ({excess:.3g} mm2, native boundary there within "
                             f"{worst:.3g} mm of the exact clearance) is taken off" if oa_tight else "") +
                            f", ca {rec.ca:.6f} matches v2 at one discretization")
                stats["omega_illcond_exact"] = stats.get("omega_illcond_exact", 0) + 1
                if oa_tight:
                    stats["omega_tight_excess"] = stats.get("omega_tight_excess", 0) + 1
                # review fix 6: only areas and shape are judged by the exact clearance; hatch and fb are checked
                # against v2's hatch / fallback algorithms run on the native Omega and revert
                selfc = self_check_hatch_fb(E, sg, shapely, V, rec, dbg)
                stats["illcond_self_checked"] = stats.get("illcond_self_checked", 0) + 1
                # review fix 8: the Hausdorff / position metrics of the rejected v2 comparison are not reported
                CP.merge_stats(stats, {k: v for k, v in first.items()
                                       if not k.startswith(("haus", "max_point", "fb_pos"))})
                done = set()
                for kind, name, ok, detail in tmp.records:
                    if kind in ("hatch", "fb"):
                        if kind not in done:
                            sok, sdet = selfc[kind]
                            chk.check(kind, name, sok, sdet if not sok else
                                      "self-checked against v2's algorithm on the native geometry (v2 ill-conditioned)")
                            done.add(kind)
                    elif not ok and kind in ("areas", "shape"):
                        if kind not in done:
                            chk.check(kind, name, True, "judged against the exact clearance (v2 ill-conditioned)")
                            done.add(kind)
                    else:
                        chk.check(kind, name, ok, detail)
                chk.logs += tmp.logs
                return
    CP.merge_stats(stats, first)
    for r in tmp.records:
        chk.check(*r)
    chk.logs += tmp.logs


def load_dumps(ddir):
    out = {}
    if os.path.isdir(ddir):
        for f in os.listdir(ddir):
            if f.startswith("k") and f.endswith(".json"):
                with open(os.path.join(ddir, f), encoding="utf-8") as fh:
                    j = json.load(fh)
                out[int(j["k"])] = j
    return out


