def t4d_job(job):
    import v2_blocks as B
    import compare_planner as CP
    part = job["part"]
    chk = Collector()
    info = {"name": f"T4d.{part}"}
    t0 = time.time()
    try:
        E, sg, shapely = _engine(job["engine"])
        sdir = os.path.join(job["work"], "t4d", part)
        os.makedirs(sdir, exist_ok=True)
        res = {}
        for d in (0.0,) + T4D_SHIFTS:
            tag = f"s{d:g}"
            stl = os.path.join(sdir, f"{part}.{tag}.stl")
            shifted_stl(os.path.join(job["mdir"], part + ".stl"), stl, T4D_ORIGIN[0] + d, T4D_ORIGIN[1] + d)
            dd = os.path.join(sdir, tag + ".dump")
            if os.path.isdir(dd):
                shutil.rmtree(dd)
            os.makedirs(dd)
            rc, data, log, _ = slice_part(job["orca"], job["datadir"], [stl], os.path.join(sdir, tag),
                                          {"ORCA_DIW_SHADOW_DUMP": dd}, arrange=False)
            chk.check("T4d", f"{part}.{tag}.rc", rc == 0 and data is not None, f"rc={rc}")
            res[d] = (data, load_dumps(dd))
        if any(v[0] is None for v in res.values()):
            return {"name": info["name"], "records": chk.records, "logs": chk.logs, "stats": {}, "info": info}
        base, bd = res[0.0]
        bb = {b.k: b for b in B.parse_records(base)[0]}
        bbeg = begin_lines(base)
        def text_input(dj):
            ls = [sg.LineString([(float(x), float(y)) for x, y in t["pts"]])
                  for key in ("text_walls", "text_paste") for t in dj["input"][key] if len(t["pts"]) >= 2]
            return sg.MultiLineString(ls)

        def wall_centroid(dj):
            # lower-left corner of the text walls' bounding box (independent of the seam positions)
            pts = [(float(x), float(y)) for t in dj["input"]["text_walls"] for x, y in t["pts"]]
            return (min(p[0] for p in pts), min(p[1] for p in pts)) if pts else None

        for d in T4D_SHIFTS:
            data, dmp = res[d]
            name = f"{part}.shift{d * 1000:g}um"
            # the part really moved by (d, d): the S1 wall vertices of the text (planner input) moved by d on average
            offs = []
            for k in sorted(set(bd) & set(dmp)):
                c0, c1 = wall_centroid(bd[k]), wall_centroid(dmp[k])
                if c0 and c1:
                    offs.append((c1[0] - c0[0], c1[1] - c0[1]))
            mx = sum(o[0] for o in offs) / len(offs) if offs else math.inf
            my = sum(o[1] for o in offs) / len(offs) if offs else math.inf
            chk.check("T4d", f"{name}.moved", min(abs(mx - d), abs(my - d)) < 0.6 * UM and max(abs(mx - d), abs(my - d)) < 2.5 * UM,
                      f"mean offset of the wall bounding box ({mx:.6f}, {my:.6f}) mm over {len(offs)} layers")
            # The slicer itself is not exactly translation-equivariant (sparse infill is anchored to the bed,
            # perimeter generation rounds in absolute coordinates): a layer whose planner input text (walls and
            # paste), moved back, differs from the base layer's by more than 1.5 um is logged and left out.
            same_in = set()
            for k in sorted(set(bd) & set(dmp)):
                h_in = CP.hausdorff(text_input(bd[k]), shapely.affinity.translate(text_input(dmp[k]), -d, -d), sg)
                if h_in <= 1.5 * UM:
                    same_in.add(k)
                else:
                    chk.log(f"T4d {name} k{k}: the slicer's own text input moved non-rigidly (Hausdorff {h_in:.3g} mm);"
                            f" layer not compared")
            # the layers whose input did not move rigidly are checked against v2 on the moved slice instead (T2(c))
            other = sorted((set(bd) & set(dmp)) - same_in)
            if other:
                import v2_hooks as H
                from compare_powder import parse_config_block, v2_config
                src = os.path.join(sdir, f"s{d:g}.stripped.gcode")
                with open(src, "wb") as fh:
                    fh.write(strip_records(data))
                cfg = v2_config(parse_config_block(data), E)
                cfg["enable_u_mex_powder_infill"] = True
                layers = {L.k: L for L in H.capture_geometry(E, cfg, src)}
                recs = {b.k: b for b in B.parse_records(data)[0]}
                sub = Collector()
                st = new_stats()
                for k in other:
                    L = layers.get(k)
                    if L is None or k not in recs:
                        sub.check("T4d", f"{name}.k{k}", False, "no v2 layer / native block")
                        continue
                    V = CP.V2Case(f"T4d.{name}.k{k}", L.model, L.prm, L.h, L.s, L.z, L.F, L.fu, L.plan, L.geom)
                    native = dmp[k].get("native")
                    compare_t2c(E, sg, shapely, sub, st, V, recs[k], dmp[k]["debug"], native,
                                mask=seam_mask(L.model, L.prm.delta, 0.0, sg), t3_extra=native_closed_loops(native, sg),
                                S_native=native_solid(native, sg))
                bad = [f for f in sub.fails]
                chk.logs += sub.logs
                chk.check("T4d", f"{name}.non_rigid_vs_v2", not bad,
                          f"{len(other)} layer(s) with a non-rigidly moved input match v2 on the moved slice "
                          f"({sub.n} checks)" + (f"; {bad[:3]}" if bad else ""))
            chk.check("T4d", f"{name}.compared", len(same_in) + len(other) == len(bd) and len(bd) > 0,
                      f"{len(same_in)} of {len(bd)} planned layers moved rigidly and are compared with the base slice")
            beg = begin_lines(data)
            keys = ("k", "z", "h", "s", "F", "fu", "fp", "st")
            same_begin = sorted(beg) == sorted(bbeg) and all(beg[k][x] == bbeg[k][x] for k in beg for x in keys)
            chk.check("T4d", f"{name}.begin", same_begin and len(beg) > 0,
                      f"{len(beg)} blocks, k/z/h/s/F/fu/fp/st equal" if same_begin else f"{sorted(beg)} vs {sorted(bbeg)}")
            sb = {b.k: b for b in B.parse_records(data)[0]}
            worst, probs = 0.0, []
            back = lambda g: shapely.affinity.translate(g, -d, -d)
            for k, b0 in bb.items():
                b1 = sb.get(k)
                if b1 is None or b0.st != "ok" or k not in same_in:
                    continue
                if b1.nc != b0.nc or b1.st != b0.st:
                    probs.append(f"k{k}: st/nc {b1.st}/{b1.nc} vs {b0.st}/{b0.nc}")
                    continue
                g0, g1 = bd.get(k, {}).get("debug"), dmp.get(k, {}).get("debug")
                if g0 is None or g1 is None:
                    probs.append(f"k{k}: no dump")
                    continue
                for key in ("cavity", "omega"):
                    a0, a1 = shapely.from_wkt(g0[key]), back(shapely.from_wkt(g1[key]))
                    if key == "cavity":
                        a0, a1 = CP.opened(a0), CP.opened(a1)
                    h = CP.hausdorff(a0.boundary, a1.boundary, sg)
                    worst = max(worst, h)
                    if h > 1.5 * UM:
                        probs.append(f"k{k}: {key} Hausdorff {h:.3g}")
                r0 = CP.runs_geom(b0.runs, sg)
                r1 = back(CP.runs_geom(b1.runs, sg))
                h = CP.hausdorff(r0, r1, sg)
                worst = max(worst, h)
                if h > 1.5 * UM:
                    # a row meeting the Omega boundary at a grazing angle theta moves its end by shift / sin(theta)
                    # along the row (the T4(b) allowance of compare_planner.runs_close)
                    moved = [B.RunRec(r.kind, [(x - d, y - d) for x, y in r.pts], r.d) for r in b1.runs]
                    ang = float(parse_cfg(base).get("diw_powder_hatch_angle", "0"))
                    O0 = shapely.from_wkt(g0["omega"])
                    ratio = max(CP.runs_close(moved, b0.runs, O0, 1.5 * UM, ang),
                                CP.runs_close(b0.runs, moved, back(shapely.from_wkt(g1["omega"])), 1.5 * UM, ang))
                    if ratio <= 1.0:
                        chk.log(f"T4d {name} k{k}: runs Hausdorff {h:.3g} mm at grazing rows (allowance ratio {ratio:.3g})")
                    else:
                        probs.append(f"k{k}: runs Hausdorff {h:.3g} (grazing allowance ratio {ratio:.3g})")
                p0 = [r.pts[0] for r in b0.runs if r.kind == "point"]
                p1 = [r.pts[0] for r in b1.runs if r.kind == "point"]
                if len(p0) != len(p1) or any(math.hypot(a[0] - b[0] + d, a[1] - b[1] + d) > 1.5 * UM for a, b in zip(p0, p1)):
                    probs.append(f"k{k}: point dwells")
                f0 = [p for f in b0.fbs for p in f.pts]
                f1 = [p for f in b1.fbs for p in f.pts]
                if len(f0) != len(f1) or any(math.hypot(a[0] - b[0] + d, a[1] - b[1] + d) > 1.5 * UM for a, b in zip(f0, f1)):
                    probs.append(f"k{k}: FB points ({len(f0)} vs {len(f1)})")
            chk.check("T4d", f"{name}.geometry", not probs, f"max Hausdorff {worst:.3g} mm" + (f"; {probs[:4]}" if probs else ""))
    except Exception as ex:
        import traceback
        chk.check("error", info["name"], False, f"{type(ex).__name__}: {ex} | {traceback.format_exc()[-600:]}")
    info["seconds"] = time.time() - t0
    return {"name": info["name"], "records": chk.records, "logs": chk.logs, "stats": {}, "info": info}


