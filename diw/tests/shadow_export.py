def matrix_jobs():
    jobs = []
    for part in SINGLE + list(PLATES):
        for wname, wov in WALLS.items():
            for fname, fov in FACTORS.items():
                if part in PLATES and fname != "base":
                    continue
                ov = dict(wov)
                ov.update(fov)
                jobs.append((part, f"{wname}.{fname}", ov))
    for part, vname, ov in EXTRA:
        jobs.append((part, f"classic.{vname}", dict(ov)))
    return jobs


def write_profiles(pdir, tag, overrides):
    os.makedirs(pdir, exist_ok=True)
    out = []
    for fn in ("flat_machine_diw.json", "flat_process_powder.json"):
        with open(os.path.join(HERE, "profiles", fn), encoding="utf-8-sig") as fh:
            d = json.load(fh)
        d.update(overrides)
        p = os.path.join(pdir, f"{tag}.{fn}")
        with open(p, "w", encoding="utf-8", newline="\n") as fh:
            json.dump(d, fh, indent=4)
        out.append(p)
    return ";".join(out)


